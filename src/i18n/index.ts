// 当前语言
let currentLang: Language = (() => {
  try {
    const saved = localStorage.getItem('landlord-ai-lang') as Language | null;
    if (saved) return saved;
  } catch { /* ignore */ }
  return 'zh-CN';
})();
const listeners: (() => void)[] = [];

export function setLanguage(lang: Language) {
  currentLang = lang;
  try { localStorage.setItem('landlord-ai-lang', lang); } catch { /* ignore */ }
  if (lang === 'ar') {
    document.documentElement.dir = 'rtl';
  } else {
    document.documentElement.dir = 'ltr';
  }
  listeners.forEach(cb => cb());
}

export function getLanguage(): Language {
  return currentLang;
}

// 启动时同步阿拉伯语 RTL 方向
try {
  document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';
} catch { /* ignore */ }

// 翻译函数
export function t(key: string): string {
  return translations[currentLang]?.[key] || translations['zh-CN']?.[key] || key;
}

// 座位显示名：座位0为人类玩家「前方」，座位1/2为 AI，随语言本地化
export function seatName(id: number): string {
  if (id === 0) return '前方';
  if (id === 1) return t('aiName1');
  if (id === 2) return t('aiName2');
  return `${t('seat')} ${id}`;
}

// 牌面点数显示名：数字/JQKA 国际通用，仅双王随语言本地化
export function rankLabel(rank: number): string {
  if (rank === 16) return t('jokerSmall');
  if (rank === 17) return t('jokerBig');
  if (rank >= 3 && rank <= 15) return rank === 11 ? 'J' : rank === 12 ? 'Q' : rank === 13 ? 'K' : rank === 14 ? 'A' : rank === 15 ? '2' : String(rank);
  return String(rank);
}

// 响应式 hook
import { useState, useEffect } from 'react';
export function useTranslation() {
  const [, setTick] = useState(0);
  useEffect(() => {
    const cb = () => setTick(t => t + 1);
    listeners.push(cb);
    return () => {
      const idx = listeners.indexOf(cb);
      if (idx >= 0) listeners.splice(idx, 1);
    };
  }, []);
  return { t, currentLang, setLanguage };
}
